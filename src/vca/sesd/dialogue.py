import json,re
from .knowledge_base import KnowledgeBase
from .rag import VectorRetriever
from .disambiguation import ambiguities,explicit_sense
from .llm import MockLLMClient
from .prompt_schema import Proposal

class Dialogue:
    def __init__(self,prompt,kb=None,llm=None,max_rounds=8,retrieval_embedder=None,rag_enabled=True,strict_llm=False):
        if not prompt.strip():raise ValueError('Initial prompt is empty')
        self.original=prompt;self.current=prompt;self.kb=kb or KnowledgeBase();self.rag=VectorRetriever(self.kb,retrieval_embedder)
        self.llm=llm or MockLLMClient();self.history=[];self.resolved={};self.max_rounds=max_rounds
        self.rag_enabled=rag_enabled;self.strict_llm=strict_llm

    def conditions(self,prompt):
        return {'has_context':len(prompt.split())>=3,'ambiguities':ambiguities(prompt,self.kb.entries,self.resolved),
                'classification':'ENGINEERING_CHOICE: minimum context rule'}

    def refine(self,feedback):
        if len(self.history)>=self.max_rounds:raise ValueError('Maximum clarification rounds reached')
        evidence=self.rag.search(feedback+' '+self.current+' '+' '.join(x['user_input'] for x in self.history[-2:])) if self.rag_enabled else []
        before=self.current
        prior_ambiguities=ambiguities(before,self.kb.entries,self.resolved) if self.rag_enabled else {}
        if not feedback.strip() and isinstance(self.llm,MockLLMClient):
            missing=self.conditions(before)
            if missing['ambiguities']:
                term,senses=next(iter(missing['ambiguities'].items()))
                return Proposal(before,'Add',question=f'For {term}, do you mean '+', '.join(senses)+'?',evidence=evidence).validate()
            return Proposal(before,'Add',question='What setting, style, or detail would you like?',evidence=evidence).validate()
        request={'current_prompt':before,'original_prompt':self.original,'user_input':feedback,
                 'history':self.history,'evidence':evidence,'knowledge':evidence,'resolved':self.resolved,
                 'unresolved_ambiguities':prior_ambiguities,
                 'output_format':['new_prompt','type'],'paper_template':'Table1 p9'}
        fallback=None
        try:
            proposal=Proposal.from_dict(json.loads(self.llm.generate(request)))
            if not isinstance(self.llm,MockLLMClient):proposal.backend=type(self.llm).__name__
        except (ValueError,TypeError,KeyError):
            if self.strict_llm:raise
            fallback='provider/schema failure; deterministic mock used'
            proposal=Proposal.from_dict(json.loads(MockLLMClient().generate(request)))
        proposal.evidence=evidence;proposal.schema_fallback=fallback
        # A real model can guess a meaning with no user response. Do not commit
        # that guess as user intent; retain provenance if a guard must ask.
        if not feedback.strip() and prior_ambiguities:
            term,senses=next(iter(prior_ambiguities.items()))
            if not proposal.question:
                proposal.question=f'Please clarify {term}: '+', '.join(senses)
                proposal.assumptions.append('question generated by deterministic ambiguity guard, not the LLM')
            if proposal.new_prompt!=before:
                proposal.assumptions.append('unsupported pre-clarification prompt change withheld')
            proposal.new_prompt=before;proposal.type='Add';proposal.target_phrase=''
        # Record a sense only after the model output actually reflects it. This
        # guard prevents a model that ignores feedback from silently corrupting H.
        processed=set()
        for e in (self.kb.entries if self.rag_enabled else []):
            term=e['term'].lower()
            if e['category']!='Polysemous Words' or term in processed:continue
            if term not in self.resolved and not re.search(r'\b'+re.escape(term)+r'\b',before,re.I):continue
            processed.add(term);match=explicit_sense(term,feedback,self.kb.entries)
            if match:
                prior=self.resolved.get(term) or (explicit_sense(term,before,self.kb.entries) or {}).get('sense')
                observed=explicit_sense(term,proposal.new_prompt,self.kb.entries)
                hits=[]
                for item in self.kb.entries:
                    if item['category']!='Polysemous Words' or item['term'].lower()!=term:continue
                    words=[item['sense'],*item['aliases']]
                    if any(re.search(r'(?<!\w)'+re.escape(w)+r'(?!\w)',proposal.new_prompt,re.I) for w in words):hits.append(item['sense'])
                has_term=bool(re.search(r'\b'+re.escape(term)+r'\b',proposal.new_prompt,re.I))
                strong_alias=any(' ' in w and re.search(r'(?<!\w)'+re.escape(w)+r'(?!\w)',proposal.new_prompt,re.I)
                                 for w in [match['sense'],*match['aliases']])
                reflected=bool(observed and observed['sense']==match['sense'] and len(set(hits))==1 and (has_term or strong_alias))
                if prior and prior!=match['sense'] and not proposal.conflicts:
                    proposal.conflicts.append({'term':term,'previous':prior,'current':match['sense'],
                        'decision':'latest explicit user intent wins','evidence_id':match['id']})
                if reflected:self.resolved[term]=match['sense']
                else:
                    proposal.assumptions.append('post-validation: requested meaning not confirmed in model output')
                    if not proposal.question:proposal.question=f'Please confirm the intended meaning of {term}: {match["sense"]}.'
        remaining=ambiguities(proposal.new_prompt,self.kb.entries,self.resolved) if self.rag_enabled else {}
        if remaining and not proposal.question:
            term,senses=next(iter(remaining.items()));proposal.question=f'Please clarify {term}: '+', '.join(senses)
            proposal.assumptions.append('question generated by deterministic ambiguity guard, not the LLM')
        if not proposal.question:self.current=proposal.new_prompt
        self.history.append({'current_prompt':before,'user_input':feedback,**proposal.as_dict()})
        return proposal.validate()
